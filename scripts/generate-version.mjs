#!/usr/bin/env node
/**
 * Write src/version.ts from package.json, so the client can report its own
 * version (`X-FirmenData-Client`, `User-Agent`) without importing
 * package.json at runtime — which would not work in every runtime or bundler.
 *
 *   node scripts/generate-version.mjs
 *
 * Runs as part of `npm run build` and `npm run generate`; CI fails when the
 * committed file differs, and test/version.test.ts pins the two together.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const { version } = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));

if (typeof version !== 'string' || !/^[0-9A-Za-z.+-]+$/.test(version)) {
  console.error(`generate-version: unusable package.json version ${JSON.stringify(version)}`);
  process.exit(1);
}

const source = `// Generated by scripts/generate-version.mjs from package.json. Do not edit.
export const VERSION = '${version}';
`;

writeFileSync(join(ROOT, 'src', 'version.ts'), source);
